-- Contatos do cliente (pessoas com quem o vendedor fala). O ERP continua sendo a fonte do cadastro
-- da empresa; contatos são dados do CRM.

CREATE TABLE contato (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT       NOT NULL REFERENCES empresa (id),
    cliente_id  BIGINT       NOT NULL REFERENCES cliente (id),
    nome        VARCHAR(120) NOT NULL,
    cargo       VARCHAR(80),
    email       VARCHAR(160),
    telefone    VARCHAR(20),
    principal   BOOLEAN      NOT NULL DEFAULT FALSE,
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_contato_cliente ON contato (empresa_id, cliente_id);
-- no máximo um contato principal ativo por cliente
CREATE UNIQUE INDEX uk_contato_principal ON contato (cliente_id) WHERE principal AND ativo;

-- Bases existentes: transforma o campo texto "contato" do cliente no contato principal.
INSERT INTO contato (empresa_id, cliente_id, nome, email, telefone, principal, ativo)
SELECT empresa_id, id, contato, email, telefone, TRUE, TRUE
  FROM cliente
 WHERE contato IS NOT NULL AND btrim(contato) <> '';
