-- Produtos de interesse da oportunidade (vindos do catálogo). Guarda snapshot de descrição/unidade/preço.
CREATE TABLE oportunidade_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       BIGINT         NOT NULL REFERENCES empresa (id),
    oportunidade_id  BIGINT         NOT NULL REFERENCES oportunidade (id) ON DELETE CASCADE,
    produto_id       BIGINT         NOT NULL REFERENCES produto (id),
    descricao        VARCHAR(200)   NOT NULL,
    unidade          VARCHAR(10)    NOT NULL,
    quantidade       NUMERIC(12, 3) NOT NULL,
    preco_unitario   NUMERIC(15, 2) NOT NULL,
    CONSTRAINT ck_oportunidade_item_qtd CHECK (quantidade > 0),
    CONSTRAINT ck_oportunidade_item_preco CHECK (preco_unitario >= 0)
);
CREATE INDEX idx_oportunidade_item_op ON oportunidade_item (empresa_id, oportunidade_id);
