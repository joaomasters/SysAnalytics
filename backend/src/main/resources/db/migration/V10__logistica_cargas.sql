-- Logística: transportadoras e follow-up de cargas (entrada = compra/importação, saída = entrega ao cliente).
-- "Atrasada" é calculada (previsão de entrega < hoje e ainda não entregue); o status gravado é só o andamento.

CREATE TABLE transportadora (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT       NOT NULL REFERENCES empresa (id),
    nome        VARCHAR(160) NOT NULL,
    documento   VARCHAR(18),
    contato     VARCHAR(120),
    email       VARCHAR(160),
    telefone    VARCHAR(20),
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_transportadora_documento ON transportadora (empresa_id, documento) WHERE documento IS NOT NULL;

CREATE TABLE carga (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id         BIGINT         NOT NULL REFERENCES empresa (id),
    sentido            VARCHAR(7)     NOT NULL,
    codigo             VARCHAR(20)    NOT NULL,
    status             VARCHAR(12)    NOT NULL,
    transportadora_id  BIGINT REFERENCES transportadora (id),
    fornecedor_id      BIGINT REFERENCES fornecedor (id),
    cliente_id         BIGINT REFERENCES cliente (id),
    numero_documento   VARCHAR(40),
    origem             VARCHAR(120),
    destino            VARCHAR(120),
    codigo_rastreio    VARCHAR(60),
    data_embarque      DATE,
    previsao_entrega   DATE           NOT NULL,
    data_entrega       DATE,
    peso_kg            NUMERIC(12, 3),
    volumes            INT,
    valor_mercadoria   NUMERIC(15, 2),
    valor_frete        NUMERIC(15, 2),
    observacao         VARCHAR(500),
    criado_por_id      BIGINT         NOT NULL REFERENCES usuario (id),
    criada_em          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_carga_codigo UNIQUE (empresa_id, codigo),
    CONSTRAINT ck_carga_sentido CHECK (sentido IN ('ENTRADA', 'SAIDA')),
    CONSTRAINT ck_carga_status CHECK (status IN ('AGUARDANDO', 'EM_TRANSITO', 'ENTREGUE', 'CANCELADA')),
    CONSTRAINT ck_carga_parceiro CHECK ((sentido = 'SAIDA' AND cliente_id IS NOT NULL)
                                     OR (sentido = 'ENTRADA' AND fornecedor_id IS NOT NULL)),
    CONSTRAINT ck_carga_entrega CHECK (status <> 'ENTREGUE' OR data_entrega IS NOT NULL),
    CONSTRAINT ck_carga_valores CHECK ((valor_frete IS NULL OR valor_frete >= 0) AND (valor_mercadoria IS NULL OR valor_mercadoria >= 0)
                                       AND (peso_kg IS NULL OR peso_kg >= 0) AND (volumes IS NULL OR volumes >= 0))
);
CREATE INDEX idx_carga_status_prev ON carga (empresa_id, status, previsao_entrega);
CREATE INDEX idx_carga_cliente ON carga (empresa_id, cliente_id);
CREATE INDEX idx_carga_transportadora ON carga (empresa_id, transportadora_id);

CREATE TABLE carga_evento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id    BIGINT       NOT NULL REFERENCES empresa (id),
    carga_id      BIGINT       NOT NULL REFERENCES carga (id) ON DELETE CASCADE,
    tipo          VARCHAR(12)  NOT NULL,
    categoria     VARCHAR(10),
    descricao     VARCHAR(500) NOT NULL,
    local         VARCHAR(120),
    ocorrido_em   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    resolvida     BOOLEAN      NOT NULL DEFAULT FALSE,
    resolvida_em  TIMESTAMPTZ,
    usuario_id    BIGINT       NOT NULL REFERENCES usuario (id),
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_carga_evento_tipo CHECK (tipo IN
        ('CRIADA', 'EMBARCADA', 'ATUALIZACAO', 'OCORRENCIA', 'ENTREGUE', 'CANCELADA', 'OBSERVACAO')),
    CONSTRAINT ck_carga_evento_categoria CHECK (categoria IS NULL OR categoria IN
        ('AVARIA', 'ATRASO', 'EXTRAVIO', 'RECUSA', 'ENDERECO', 'DOCUMENTO', 'OUTRO')),
    CONSTRAINT ck_carga_evento_ocorrencia CHECK (tipo <> 'OCORRENCIA' OR categoria IS NOT NULL)
);
CREATE INDEX idx_carga_evento_carga ON carga_evento (carga_id, ocorrido_em);
CREATE INDEX idx_carga_evento_ocorrencia ON carga_evento (empresa_id, tipo, resolvida);
