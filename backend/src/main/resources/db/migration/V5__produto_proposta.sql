-- Catálogo de produtos e propostas comerciais ligadas às oportunidades.

CREATE TABLE produto (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      BIGINT         NOT NULL REFERENCES empresa (id),
    codigo          VARCHAR(40)    NOT NULL,
    nome            VARCHAR(160)   NOT NULL,
    descricao       VARCHAR(500),
    unidade         VARCHAR(10)    NOT NULL DEFAULT 'UN',
    preco_unitario  NUMERIC(15, 2) NOT NULL,
    ativo           BOOLEAN        NOT NULL DEFAULT TRUE,
    criado_em       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_produto_empresa_codigo UNIQUE (empresa_id, codigo),
    CONSTRAINT ck_produto_preco CHECK (preco_unitario >= 0)
);

CREATE TABLE proposta (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id           BIGINT        NOT NULL REFERENCES empresa (id),
    oportunidade_id      BIGINT        NOT NULL REFERENCES oportunidade (id),
    criada_por_id        BIGINT        NOT NULL REFERENCES usuario (id),
    status               VARCHAR(10)   NOT NULL,
    validade_ate         DATE,
    condicoes_pagamento  VARCHAR(200),
    observacoes          VARCHAR(1000),
    criada_em            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizada_em        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_proposta_status CHECK (status IN ('RASCUNHO', 'ENVIADA', 'ACEITA', 'RECUSADA'))
);
CREATE INDEX idx_proposta_oportunidade ON proposta (empresa_id, oportunidade_id);

-- Os itens guardam uma "foto" do produto (descrição e preço): mudar o catálogo não altera propostas antigas.
CREATE TABLE proposta_item (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id           BIGINT         NOT NULL REFERENCES empresa (id),
    proposta_id          BIGINT         NOT NULL REFERENCES proposta (id) ON DELETE CASCADE,
    produto_id           BIGINT         REFERENCES produto (id),
    descricao            VARCHAR(160)   NOT NULL,
    unidade              VARCHAR(10)    NOT NULL,
    quantidade           NUMERIC(12, 3) NOT NULL,
    preco_unitario       NUMERIC(15, 2) NOT NULL,
    desconto_percentual  NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    CONSTRAINT ck_item_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_preco CHECK (preco_unitario >= 0),
    CONSTRAINT ck_item_desconto CHECK (desconto_percentual BETWEEN 0 AND 100)
);
CREATE INDEX idx_proposta_item_proposta ON proposta_item (proposta_id);
