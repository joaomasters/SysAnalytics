-- Gestão de usuários, senha e trilha de segurança.

ALTER TABLE usuario
    ADD COLUMN token_versao      INT         NOT NULL DEFAULT 0,      -- incrementa para invalidar sessões abertas
    ADD COLUMN tentativas_falhas INT         NOT NULL DEFAULT 0,
    ADD COLUMN bloqueado_ate     TIMESTAMPTZ,
    ADD COLUMN senha_temporaria  BOOLEAN     NOT NULL DEFAULT FALSE,  -- true: o usuário precisa trocar a senha no próximo acesso
    ADD COLUMN senha_alterada_em TIMESTAMPTZ,
    ADD COLUMN atualizado_em     TIMESTAMPTZ;

CREATE TABLE evento_seguranca (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT       NOT NULL REFERENCES empresa (id),
    usuario_id  BIGINT       REFERENCES usuario (id),   -- quem executou
    alvo_id     BIGINT       REFERENCES usuario (id),   -- quem foi afetado
    tipo        VARCHAR(30)  NOT NULL,
    detalhe     VARCHAR(300),
    ip          VARCHAR(45),
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_evento_seguranca_empresa ON evento_seguranca (empresa_id, criado_em DESC);
