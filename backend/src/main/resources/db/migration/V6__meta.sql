-- Meta mensal de faturamento por vendedor. O realizado vem do faturamento (ERP); nada é duplicado aqui.

CREATE TABLE meta (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id         BIGINT         NOT NULL REFERENCES empresa (id),
    vendedor_id        BIGINT         NOT NULL REFERENCES vendedor (id),
    competencia        DATE           NOT NULL,
    valor_meta         NUMERIC(15, 2) NOT NULL,
    atualizada_por_id  BIGINT         NOT NULL REFERENCES usuario (id),
    atualizada_em      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_meta_vendedor_mes UNIQUE (empresa_id, vendedor_id, competencia),
    CONSTRAINT ck_meta_valor CHECK (valor_meta >= 0),
    -- competência é sempre o primeiro dia do mês
    CONSTRAINT ck_meta_competencia CHECK (EXTRACT(DAY FROM competencia) = 1)
);
CREATE INDEX idx_meta_empresa_competencia ON meta (empresa_id, competencia);
