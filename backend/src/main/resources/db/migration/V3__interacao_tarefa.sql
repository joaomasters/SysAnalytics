-- Interações (histórico do relacionamento) e tarefas (próximos passos do vendedor).

CREATE TABLE interacao (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT        NOT NULL REFERENCES empresa (id),
    cliente_id  BIGINT        NOT NULL REFERENCES cliente (id),
    contato_id  BIGINT        REFERENCES contato (id),
    usuario_id  BIGINT        NOT NULL REFERENCES usuario (id),
    tipo        VARCHAR(10)   NOT NULL,
    data_hora   TIMESTAMPTZ   NOT NULL,
    resumo      VARCHAR(1000) NOT NULL,
    criado_em   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_interacao_tipo CHECK (tipo IN ('LIGACAO', 'EMAIL', 'VISITA', 'WHATSAPP', 'REUNIAO', 'OUTRO'))
);
CREATE INDEX idx_interacao_cliente ON interacao (empresa_id, cliente_id, data_hora DESC);

CREATE TABLE tarefa (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      BIGINT        NOT NULL REFERENCES empresa (id),
    cliente_id      BIGINT        NOT NULL REFERENCES cliente (id),
    responsavel_id  BIGINT        NOT NULL REFERENCES usuario (id),
    criada_por_id   BIGINT        NOT NULL REFERENCES usuario (id),
    titulo          VARCHAR(160)  NOT NULL,
    descricao       VARCHAR(1000),
    prazo           DATE          NOT NULL,
    status          VARCHAR(10)   NOT NULL,
    origem          VARCHAR(10)   NOT NULL,
    notificacao_id  BIGINT        REFERENCES notificacao_alerta (id),
    resultado       VARCHAR(15),
    concluida_em    TIMESTAMPTZ,
    criada_em       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_tarefa_status CHECK (status IN ('ABERTA', 'CONCLUIDA', 'CANCELADA')),
    CONSTRAINT ck_tarefa_origem CHECK (origem IN ('MANUAL', 'ALERTA')),
    CONSTRAINT ck_tarefa_resultado CHECK (resultado IS NULL
        OR resultado IN ('REATIVADO', 'EM_NEGOCIACAO', 'SEM_RETORNO', 'PERDIDO', 'OUTRO'))
);
CREATE INDEX idx_tarefa_responsavel ON tarefa (empresa_id, responsavel_id, status, prazo);
CREATE INDEX idx_tarefa_cliente ON tarefa (empresa_id, cliente_id);
-- um alerta gera no máximo uma tarefa
CREATE UNIQUE INDEX uk_tarefa_notificacao ON tarefa (notificacao_id) WHERE notificacao_id IS NOT NULL;
