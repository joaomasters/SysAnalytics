-- Financeiro: contas a receber (títulos, baixas) e cobrança (ações de follow-up e promessas de pagamento).
-- A situação "A VENCER" / "VENCIDO" é calculada na consulta a partir da data de vencimento: não é gravada.

CREATE TABLE titulo_receber (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id        BIGINT         NOT NULL REFERENCES empresa (id),
    cliente_id        BIGINT         NOT NULL REFERENCES cliente (id),
    numero_documento  VARCHAR(40)    NOT NULL,
    parcela           INT            NOT NULL DEFAULT 1,
    total_parcelas    INT            NOT NULL DEFAULT 1,
    descricao         VARCHAR(200),
    data_emissao      DATE           NOT NULL,
    data_vencimento   DATE           NOT NULL,
    valor             NUMERIC(15, 2) NOT NULL,
    valor_pago        NUMERIC(15, 2) NOT NULL DEFAULT 0,
    data_quitacao     DATE,
    status            VARCHAR(10)    NOT NULL,
    criado_por_id     BIGINT         NOT NULL REFERENCES usuario (id),
    criado_em         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_titulo_receber_doc UNIQUE (empresa_id, numero_documento, parcela),
    CONSTRAINT ck_titulo_receber_status CHECK (status IN ('ABERTO', 'PARCIAL', 'PAGO', 'CANCELADO')),
    CONSTRAINT ck_titulo_receber_valor CHECK (valor > 0),
    CONSTRAINT ck_titulo_receber_pago CHECK (valor_pago >= 0 AND valor_pago <= valor),
    CONSTRAINT ck_titulo_receber_parcela CHECK (parcela >= 1 AND total_parcelas >= parcela)
);
CREATE INDEX idx_titulo_receber_status_venc ON titulo_receber (empresa_id, status, data_vencimento);
CREATE INDEX idx_titulo_receber_cliente ON titulo_receber (empresa_id, cliente_id);

CREATE TABLE baixa_receber (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       BIGINT         NOT NULL REFERENCES empresa (id),
    titulo_id        BIGINT         NOT NULL REFERENCES titulo_receber (id) ON DELETE CASCADE,
    data_baixa       DATE           NOT NULL,
    valor            NUMERIC(15, 2) NOT NULL,
    forma_pagamento  VARCHAR(15)    NOT NULL,
    observacao       VARCHAR(300),
    usuario_id       BIGINT         NOT NULL REFERENCES usuario (id),
    criada_em        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_baixa_receber_valor CHECK (valor > 0),
    CONSTRAINT ck_baixa_receber_forma CHECK (forma_pagamento IN
        ('PIX', 'BOLETO', 'TRANSFERENCIA', 'CARTAO', 'DINHEIRO', 'CHEQUE', 'OUTRO'))
);
CREATE INDEX idx_baixa_receber_titulo ON baixa_receber (titulo_id);
CREATE INDEX idx_baixa_receber_data ON baixa_receber (empresa_id, data_baixa);

CREATE TABLE cobranca_acao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      BIGINT         NOT NULL REFERENCES empresa (id),
    titulo_id       BIGINT         NOT NULL REFERENCES titulo_receber (id) ON DELETE CASCADE,
    cliente_id      BIGINT         NOT NULL REFERENCES cliente (id),
    tipo            VARCHAR(10)    NOT NULL,
    resultado       VARCHAR(20)    NOT NULL,
    resumo          VARCHAR(500)   NOT NULL,
    promessa_data   DATE,
    promessa_valor  NUMERIC(15, 2),
    usuario_id      BIGINT         NOT NULL REFERENCES usuario (id),
    criada_em       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_cobranca_tipo CHECK (tipo IN ('LIGACAO', 'WHATSAPP', 'EMAIL', 'VISITA', 'OUTRO')),
    CONSTRAINT ck_cobranca_resultado CHECK (resultado IN
        ('SEM_RETORNO', 'PROMESSA', 'CONTESTACAO', 'PAGAMENTO_INFORMADO', 'OUTRO')),
    CONSTRAINT ck_cobranca_promessa CHECK (resultado <> 'PROMESSA' OR promessa_data IS NOT NULL)
);
CREATE INDEX idx_cobranca_titulo ON cobranca_acao (titulo_id);
CREATE INDEX idx_cobranca_empresa_promessa ON cobranca_acao (empresa_id, promessa_data);
