-- Schema inicial multi-tenant. Toda tabela de negócio carrega empresa_id.
-- As tabelas BATCH_* do Spring Batch são criadas pelo próprio framework.

CREATE TABLE empresa (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(160) NOT NULL,
    cnpj       VARCHAR(18)  NOT NULL UNIQUE,
    ativa      BOOLEAN      NOT NULL DEFAULT TRUE,
    criada_em  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE vendedor (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT       NOT NULL REFERENCES empresa (id),
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(160) NOT NULL,
    telefone   VARCHAR(20),
    carteira   VARCHAR(80)  NOT NULL,
    CONSTRAINT uk_vendedor_empresa_email UNIQUE (empresa_id, email)
);

CREATE TABLE usuario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       BIGINT       NOT NULL REFERENCES empresa (id),
    nome             VARCHAR(120) NOT NULL,
    email            VARCHAR(160) NOT NULL,
    senha_hash       VARCHAR(100) NOT NULL,
    perfil           VARCHAR(10)  NOT NULL,
    vendedor_id      BIGINT REFERENCES vendedor (id),
    ativo            BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ultimo_login_em  TIMESTAMPTZ,
    -- e-mail único globalmente: o login não precisa informar a empresa
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN', 'GESTOR', 'VENDEDOR')),
    CONSTRAINT ck_usuario_vendedor CHECK (perfil <> 'VENDEDOR' OR vendedor_id IS NOT NULL)
);
CREATE INDEX idx_usuario_empresa ON usuario (empresa_id);

CREATE TABLE cliente (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL REFERENCES empresa (id),
    cnpj           VARCHAR(18)  NOT NULL,
    razao_social   VARCHAR(160) NOT NULL,
    nome_fantasia  VARCHAR(120) NOT NULL,
    contato        VARCHAR(120),
    email          VARCHAR(160),
    telefone       VARCHAR(20),
    cidade         VARCHAR(80),
    uf             VARCHAR(2),
    segmento       VARCHAR(60),
    data_cadastro  DATE         NOT NULL,
    vendedor_id    BIGINT       NOT NULL REFERENCES vendedor (id),
    CONSTRAINT uk_cliente_empresa_cnpj UNIQUE (empresa_id, cnpj)
);
CREATE INDEX idx_cliente_vendedor ON cliente (vendedor_id);

CREATE TABLE faturamento (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id        BIGINT         NOT NULL REFERENCES empresa (id),
    numero_nota       VARCHAR(20)    NOT NULL,
    data_faturamento  DATE           NOT NULL,
    valor_total       NUMERIC(15, 2) NOT NULL,
    cliente_id        BIGINT         NOT NULL REFERENCES cliente (id),
    vendedor_id       BIGINT         NOT NULL REFERENCES vendedor (id),
    CONSTRAINT uk_faturamento_empresa_nota UNIQUE (empresa_id, numero_nota)
);
CREATE INDEX idx_faturamento_data ON faturamento (data_faturamento);
CREATE INDEX idx_faturamento_cliente_data ON faturamento (cliente_id, data_faturamento);
CREATE INDEX idx_faturamento_empresa_data ON faturamento (empresa_id, data_faturamento);

CREATE TABLE custo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      BIGINT         NOT NULL REFERENCES empresa (id),
    descricao       VARCHAR(160)   NOT NULL,
    categoria       VARCHAR(60)    NOT NULL,
    tipo            VARCHAR(10)    NOT NULL,
    periodicidade   VARCHAR(10)    NOT NULL,
    data_lancamento DATE           NOT NULL,
    valor           NUMERIC(15, 2) NOT NULL
);
CREATE INDEX idx_custo_data ON custo (data_lancamento);
CREATE INDEX idx_custo_empresa_data ON custo (empresa_id, data_lancamento);

CREATE TABLE notificacao_alerta (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       BIGINT       NOT NULL REFERENCES empresa (id),
    cliente_id       BIGINT       NOT NULL,
    cliente_nome     VARCHAR(120) NOT NULL,
    vendedor_id      BIGINT,
    vendedor_nome    VARCHAR(120),
    nivel            VARCHAR(10)  NOT NULL,
    dias_inatividade INTEGER,
    mensagem         VARCHAR(400) NOT NULL,
    lida             BOOLEAN      NOT NULL,
    data_referencia  DATE         NOT NULL,
    criada_em        TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_notificacao_cliente_nivel_dia UNIQUE (cliente_id, nivel, data_referencia)
);
CREATE INDEX idx_notificacao_lida ON notificacao_alerta (lida, criada_em);
CREATE INDEX idx_notificacao_empresa ON notificacao_alerta (empresa_id, criada_em);
