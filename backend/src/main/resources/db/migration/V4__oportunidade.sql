-- Funil de vendas: oportunidades em etapas fixas.

CREATE TABLE oportunidade (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id                BIGINT         NOT NULL REFERENCES empresa (id),
    cliente_id                BIGINT         NOT NULL REFERENCES cliente (id),
    responsavel_id            BIGINT         NOT NULL REFERENCES usuario (id),
    criada_por_id             BIGINT         NOT NULL REFERENCES usuario (id),
    titulo                    VARCHAR(160)   NOT NULL,
    descricao                 VARCHAR(1000),
    valor_estimado            NUMERIC(15, 2) NOT NULL,
    probabilidade             INTEGER        NOT NULL,
    etapa                     VARCHAR(15)    NOT NULL,
    data_prevista_fechamento  DATE,
    motivo_perda              VARCHAR(15),
    fechada_em                TIMESTAMPTZ,
    criada_em                 TIMESTAMPTZ    NOT NULL DEFAULT now(),
    atualizada_em             TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_oportunidade_etapa CHECK (etapa IN
        ('PROSPECCAO', 'QUALIFICACAO', 'PROPOSTA', 'NEGOCIACAO', 'GANHA', 'PERDIDA')),
    CONSTRAINT ck_oportunidade_probabilidade CHECK (probabilidade BETWEEN 0 AND 100),
    CONSTRAINT ck_oportunidade_valor CHECK (valor_estimado >= 0),
    CONSTRAINT ck_oportunidade_motivo CHECK (motivo_perda IS NULL OR motivo_perda IN
        ('PRECO', 'CONCORRENTE', 'SEM_ORCAMENTO', 'SEM_RETORNO', 'OUTRO')),
    -- perdida exige motivo
    CONSTRAINT ck_oportunidade_perda CHECK (etapa <> 'PERDIDA' OR motivo_perda IS NOT NULL)
);
CREATE INDEX idx_oportunidade_empresa_etapa ON oportunidade (empresa_id, etapa);
CREATE INDEX idx_oportunidade_responsavel ON oportunidade (empresa_id, responsavel_id);
CREATE INDEX idx_oportunidade_cliente ON oportunidade (empresa_id, cliente_id);
