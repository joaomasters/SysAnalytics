-- Financeiro: fornecedores e contas a pagar (com pagamentos). Só gestor/admin enxergam.
-- A situação "A VENCER" / "VENCIDO" é calculada na consulta, como no contas a receber.

CREATE TABLE fornecedor (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT       NOT NULL REFERENCES empresa (id),
    nome        VARCHAR(160) NOT NULL,
    documento   VARCHAR(18),
    contato     VARCHAR(120),
    email       VARCHAR(160),
    telefone    VARCHAR(20),
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_fornecedor_documento ON fornecedor (empresa_id, documento) WHERE documento IS NOT NULL;
CREATE INDEX idx_fornecedor_empresa ON fornecedor (empresa_id, nome);

CREATE TABLE conta_pagar (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id        BIGINT         NOT NULL REFERENCES empresa (id),
    fornecedor_id     BIGINT         NOT NULL REFERENCES fornecedor (id),
    numero_documento  VARCHAR(40)    NOT NULL,
    parcela           INT            NOT NULL DEFAULT 1,
    total_parcelas    INT            NOT NULL DEFAULT 1,
    descricao         VARCHAR(200),
    categoria         VARCHAR(15)    NOT NULL,
    data_emissao      DATE           NOT NULL,
    data_vencimento   DATE           NOT NULL,
    valor             NUMERIC(15, 2) NOT NULL,
    valor_pago        NUMERIC(15, 2) NOT NULL DEFAULT 0,
    data_quitacao     DATE,
    status            VARCHAR(10)    NOT NULL,
    criado_por_id     BIGINT         NOT NULL REFERENCES usuario (id),
    criado_em         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_conta_pagar_doc UNIQUE (empresa_id, fornecedor_id, numero_documento, parcela),
    CONSTRAINT ck_conta_pagar_status CHECK (status IN ('ABERTO', 'PARCIAL', 'PAGO', 'CANCELADO')),
    CONSTRAINT ck_conta_pagar_categoria CHECK (categoria IN
        ('MERCADORIA', 'FRETE', 'IMPOSTOS', 'PESSOAL', 'ALUGUEL', 'UTILIDADES', 'MARKETING', 'SERVICOS', 'OUTROS')),
    CONSTRAINT ck_conta_pagar_valor CHECK (valor > 0),
    CONSTRAINT ck_conta_pagar_pago CHECK (valor_pago >= 0 AND valor_pago <= valor),
    CONSTRAINT ck_conta_pagar_parcela CHECK (parcela >= 1 AND total_parcelas >= parcela)
);
CREATE INDEX idx_conta_pagar_status_venc ON conta_pagar (empresa_id, status, data_vencimento);
CREATE INDEX idx_conta_pagar_fornecedor ON conta_pagar (empresa_id, fornecedor_id);
CREATE INDEX idx_conta_pagar_emissao ON conta_pagar (empresa_id, categoria, data_emissao);

CREATE TABLE baixa_pagar (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       BIGINT         NOT NULL REFERENCES empresa (id),
    conta_id         BIGINT         NOT NULL REFERENCES conta_pagar (id) ON DELETE CASCADE,
    data_pagamento   DATE           NOT NULL,
    valor            NUMERIC(15, 2) NOT NULL,
    forma_pagamento  VARCHAR(15)    NOT NULL,
    observacao       VARCHAR(300),
    usuario_id       BIGINT         NOT NULL REFERENCES usuario (id),
    criada_em        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_baixa_pagar_valor CHECK (valor > 0),
    CONSTRAINT ck_baixa_pagar_forma CHECK (forma_pagamento IN
        ('PIX', 'BOLETO', 'TRANSFERENCIA', 'CARTAO', 'DINHEIRO', 'CHEQUE', 'OUTRO'))
);
CREATE INDEX idx_baixa_pagar_conta ON baixa_pagar (conta_id);
CREATE INDEX idx_baixa_pagar_data ON baixa_pagar (empresa_id, data_pagamento);
